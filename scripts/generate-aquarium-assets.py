#!/usr/bin/env python3
"""Keep approved native-pixel prototype artwork and firmware artwork identical."""
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
fish=re.findall(r"^  '([.#w]+)',",(ROOT/'prototypes/aquarium/app.mjs').read_text(),re.M)
logo=re.findall(r"^  '([.#w]+)',",(ROOT/'prototypes/aquarium/logo.mjs').read_text(),re.M)
assert len(fish)==14 and all(len(r)==27 for r in fish)
assert len(logo)==32 and all(len(r)==48 for r in logo)
source='#pragma once\n// Generated by scripts/generate-aquarium-assets.py from approved original artwork.\nnamespace tank {\n'
for name,rows in [('FishArt',fish),('Logo',logo)]:
    source+=f'inline constexpr const char *{name}[] = {{\n'+''.join('  "'+r+'",\n' for r in rows)+'};\n'
(ROOT/'firmware/main/aquarium_assets.hpp').write_text(source+'}\n')
